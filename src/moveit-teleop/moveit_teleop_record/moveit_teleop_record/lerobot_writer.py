"""Aligned bundles -> a LeRobot v2.1 dataset that GR00T and openpi both load.

Run by `convert`, in the LeRobot environment -- NOT imported by ROS code. It
must not import anything from ROS or from this package, because the two
environments cannot share an interpreter. So it is a single self-contained
script, invoked by path.

Why v2.1, and why through LeRobot itself
----------------------------------------
* openpi (pi0 / pi0.5) pins lerobot to commit 0cf8648, whose CODEBASE_VERSION is
  "v2.1". It loads datasets with that exact library.
* Isaac-GR00T requires LeRobot v2 and ships a v3->v2 converter. Its own demo
  dataset (demo_data/cube_to_bowl_5) is a stock v2.1 dataset -- the default
  columns, AV1 video -- plus one extra file, meta/modality.json.

So the dataset is written by that pinned lerobot's own LeRobotDataset rather
than by hand. That guarantees the details that are easy to get subtly wrong:
the dataset-wide `index`, per-episode stats, AV1 encoding with a keyframe every
second frame (fast random access at training time), and timestamps exactly on
`frame_index / fps` -- which the loader checks to 0.1 ms.

Then the dataset is loaded back with that same library, and checked, before this
script reports success.
"""

from __future__ import annotations

import argparse
import functools
import json
import shutil
import sys
from pathlib import Path

import numpy as np

EXPORT_META = 'moveit_teleop_export.json'


# ---- GR00T modality.json, and a modality config to train with ------------

def group_spans(groups) -> dict:
    """``{group: {start, end}}`` in vector order, from the robot model's groups."""
    spans, start = {}, 0
    for g in groups:
        spans[g['name']] = {'start': start, 'end': start + len(g['joints'])}
        start += len(g['joints'])
    return spans


def build_modality(groups, cameras) -> dict:
    """GR00T's meta/modality.json, in the shape of its own demo dataset.

    Groups come from the SRDF via robot_model.py -- the arm group, then the
    gripper group if the robot has one. The task description maps straight onto
    the stock `task_index` column, exactly as GR00T's demo_data does.
    """
    spans = group_spans(groups)
    return {
        'state': spans,
        'action': {k: dict(v) for k, v in spans.items()},
        'video': {cam: {'original_key': f'observation.images.{cam}'}
                  for cam in cameras},
        'annotation': {'human.task_description': {'original_key': 'task_index'}},
    }


GR00T_CONFIG = '''"""GR00T modality config for this dataset. Generated by moveit_teleop_record convert.

Robot {robot_name!r} (LeRobot robot_type {robot_type!r}), described by
{config}

    uv run python gr00t/experiment/launch_finetune.py \\
        --base-model-path nvidia/GR00T-N1.7-3B \\
        --dataset-path <this directory> \\
        --embodiment-tag NEW_EMBODIMENT \\
        --modality-config-path <this directory>/gr00t_modality_config.py

Rewritten on every export: change the robot config's `dataset.gr00t` section
rather than this file. GR00T imports it by file name, and computes
meta/stats.json and relative_stats.json itself on first use.

Layout, from the robot model:
{layout}
Action horizon {horizon} steps at {fps} fps = {lookahead:.2f} s of lookahead.
"""

from gr00t.configs.data.embodiment_configs import register_modality_config
from gr00t.data.embodiment_tags import EmbodimentTag
from gr00t.data.types import (
    ActionConfig,
    ActionFormat,
    ActionRepresentation,
    ActionType,
    ModalityConfig,
)

config = {{
    "video": ModalityConfig(delta_indices=[0], modality_keys={cameras!r}),
    "state": ModalityConfig(delta_indices=[0], modality_keys={groups!r}),
    "action": ModalityConfig(
        delta_indices=list(range({horizon})),
        modality_keys={groups!r},
        action_configs=[
{action_configs}
        ],
    ),
    "language": ModalityConfig(
        delta_indices=[0],
        modality_keys=["annotation.human.task_description"],
    ),
}}

register_modality_config(config, embodiment_tag=EmbodimentTag.NEW_EMBODIMENT)
'''


def build_gr00t_config(export: dict, cameras, fps: int) -> str:
    robot, gr00t = export['robot'], export['dataset']['gr00t']
    groups = robot['groups']
    rep = {'arm': gr00t['arm_action'], 'gripper': gr00t['gripper_action']}
    actions = '\n'.join(
        f'            # {g["name"]}: {", ".join(g["joints"])}\n'
        f'            ActionConfig(rep=ActionRepresentation.{rep[g["name"]].upper()}, '
        'type=ActionType.NON_EEF, format=ActionFormat.DEFAULT),'
        for g in groups)
    spans = group_spans(groups)
    layout = ''.join(
        f'    {g["name"]:8s} [{spans[g["name"]]["start"]}:{spans[g["name"]]["end"]}]  '
        f'{", ".join(f"{j} ({u})" for j, u in zip(g["joints"], g["units"]))}  '
        f'-- {rep[g["name"]]} action\n'
        for g in groups)
    horizon = int(gr00t['action_horizon'])
    return GR00T_CONFIG.format(
        robot_name=robot['robot_name'], robot_type=robot['robot_type'],
        config=robot['config'], layout=layout, horizon=horizon, fps=fps,
        lookahead=horizon / fps, cameras=list(cameras),
        groups=[g['name'] for g in groups], action_configs=actions)


# ---- images ---------------------------------------------------------------

def parse_size(text):
    if text in (None, '', 'native'):
        return None
    w, h = text.lower().split('x')
    return int(w), int(h)


def decode(path: Path, size):
    import cv2
    img = cv2.imdecode(np.fromfile(str(path), np.uint8), cv2.IMREAD_COLOR)
    if img is None:
        raise RuntimeError(f'cannot decode {path}')
    img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    if size is not None and (img.shape[1], img.shape[0]) != size:
        img = cv2.resize(img, size, interpolation=cv2.INTER_AREA)
    return img


# ---- writing --------------------------------------------------------------

def load_bundle(path: Path) -> dict:
    meta = json.loads((path / 'meta.json').read_text())
    arrays = np.load(path / 'arrays.npz')
    meta['state'] = arrays['state'].astype(np.float32)
    meta['action'] = arrays['action'].astype(np.float32)
    meta['path'] = path
    return meta


def write(bundles, root: Path, repo_id: str, size, vcodec: str,
          export: dict, append: bool, overwrite: bool = False) -> dict:
    from lerobot.common.datasets import lerobot_dataset as lds
    from lerobot.common.datasets.lerobot_dataset import LeRobotDataset

    if vcodec == 'h264':
        # save_episode always encodes with the library default (AV1, crf 30),
        # so the codec is the one thing patched. crf too: lerobot passes the same
        # number to every encoder, and 30 -- fine for AV1 -- is visibly soft on
        # x264, where 23 is the default. Measured on four Piper episodes, h264
        # at 23 is about 1.5x the size of lerobot's AV1 (6.4 MB against 4.4 MB).
        lds.encode_video_frames = functools.partial(lds.encode_video_frames,
                                                    vcodec='h264', crf=23)

    first = bundles[0]
    fps = int(first['fps'])
    sample_img = decode(first['path'] / first['cameras'][0] / '000000.jpg', size)
    height, width = sample_img.shape[:2]
    for b in bundles:
        for key in ('fps', 'state_names', 'action_names', 'cameras', 'groups'):
            if b[key] != first[key]:
                raise SystemExit(
                    f"{b['source']}: {key} is {b[key]!r} but {first['source']} "
                    f"has {first[key]!r}; one dataset needs one shape")

    features = {
        'observation.state': {'dtype': 'float32',
                              'shape': (len(first['state_names']),),
                              'names': list(first['state_names'])},
        'action': {'dtype': 'float32',
                   'shape': (len(first['action_names']),),
                   'names': list(first['action_names'])},
    }
    for cam in first['cameras']:
        features[f'observation.images.{cam}'] = {
            'dtype': 'video', 'shape': (height, width, 3),
            'names': ['height', 'width', 'channels']}

    if append and (root / 'meta' / 'info.json').exists():
        ds = LeRobotDataset(repo_id, root=root)
        if ds.fps != fps:
            raise SystemExit(f'existing dataset is {ds.fps} fps, new episodes are {fps}')
        ds.start_image_writer(num_processes=0, num_threads=4)
        print(f'appending to {root} ({ds.meta.total_episodes} episode(s) already)')
    else:
        if root.exists() and any(root.iterdir()):
            # Only ever delete something that is demonstrably a LeRobot dataset,
            # and only when asked to. A mistyped output path must not be able to
            # take a directory of anything else with it.
            if not (root / 'meta' / 'info.json').exists():
                raise SystemExit(f'{root} is not empty and is not a LeRobot '
                                 'dataset; refusing to replace it')
            if not overwrite:
                raise SystemExit(f'{root} is already a dataset; pass --append '
                                 'or --overwrite')
            shutil.rmtree(root)
        elif root.exists():
            root.rmdir()   # empty: LeRobot wants to create it itself
        ds = LeRobotDataset.create(repo_id, fps=fps, root=root,
                                   robot_type=export['robot']['robot_type'],
                                   features=features,
                                   use_videos=True, image_writer_threads=4)
        print(f'creating {root} at {fps} fps, images {width}x{height}, {vcodec}')

    written = []
    for b in bundles:
        episode_index = ds.meta.total_episodes
        for k in range(len(b['state'])):
            frame = {'observation.state': b['state'][k],
                     'action': b['action'][k],
                     'task': b['task']}
            for cam in b['cameras']:
                frame[f'observation.images.{cam}'] = decode(
                    b['path'] / cam / f'{k:06d}.jpg', size)
            ds.add_frame(frame)
        ds.save_episode()
        written.append({'episode_index': episode_index, 'source': b['source'],
                        'frames': len(b['state']), 'task': b['task'],
                        'sync': b['report']})
        print(f"  episode {episode_index}: {b['source']}  {len(b['state'])} frames, "
              f"task {b['task']!r}")
    ds.stop_image_writer()

    modality = build_modality(first['groups'], first['cameras'])
    (root / 'meta' / 'modality.json').write_text(json.dumps(modality, indent=4))
    (root / 'gr00t_modality_config.py').write_text(
        build_gr00t_config(export, first['cameras'], fps))

    provenance = root / 'meta' / EXPORT_META
    record = json.loads(provenance.read_text()) if provenance.exists() else {}
    if isinstance(record, list):              # an export from before this format
        record = {'episodes': record}
    record['robot'] = export['robot']
    record['dataset_settings'] = export['dataset']
    record['episodes'] = record.get('episodes', []) + written
    provenance.write_text(json.dumps(record, indent=2))
    write_readme(root, record)
    return {'fps': fps, 'size': (width, height), 'written': written,
            'features': features}


# ---- dataset card ---------------------------------------------------------

def write_readme(root: Path, record: dict) -> None:
    """A README.md at the dataset root: what is in it, and how to use it."""
    info = json.loads((root / 'meta' / 'info.json').read_text())
    tasks = [json.loads(l)['task'] for l in
             (root / 'meta' / 'tasks.jsonl').read_text().splitlines() if l]
    robot, fps = record['robot'], info['fps']
    video = [k for k, v in info['features'].items() if v['dtype'] == 'video']
    lines = [
        f"# {root.name}", '',
        f"LeRobot {info['codebase_version']} dataset of teleoperated demonstrations on "
        f"**{robot['robot_name']}**, exported by `moveit_teleop_record convert`.", '',
        '| | |', '|---|---|',
        f"| Episodes | {info['total_episodes']} |",
        f"| Frames | {info['total_frames']} at {fps} fps "
        f"({info['total_frames'] / fps:.1f} s) |",
        f"| Tasks | {', '.join(repr(t) for t in tasks)} |",
        f"| robot_type | `{info['robot_type']}` |",
        f"| Robot config | `{robot['config']}` |", '',
        '## Features', '',
        '| Feature | Shape | Contents |', '|---|---|---|',
    ]
    for g in robot['groups']:
        joints = ', '.join(f"{j} ({u})" for j, u in zip(g['joints'], g['units']))
        lines.append(f"| `observation.state[{g['start']}:{g['end']}]` | {g['end'] - g['start']} | "
                     f"{g['name']} (SRDF `{g['srdf_group']}`), MEASURED: {joints} |")
    for g in robot['groups']:
        lines.append(f"| `action[{g['start']}:{g['end']}]` | {g['end'] - g['start']} | "
                     f"{g['name']}, COMMANDED, same joints and units |")
    for key in video:
        h, w, c = info['features'][key]['shape']
        codec = info['features'][key]['info']['video.codec']
        lines.append(f"| `{key}` | {h}x{w}x{c} | {codec} video at {fps} fps |")
    lines += ['', '## Time alignment', '',
              'Each frame is one real camera frame. Joint state and action are '
              'interpolated to that frame\'s CAPTURE time (header stamp), not the '
              'time it was received, and each episode is trimmed to the span the '
              'operator was driving.', '',
              '| Episode | Source | Frames kept | Camera latency corrected | '
              'Image-motion vs joint-speed |', '|---|---|---|---|---|']
    for ep in record['episodes']:
        s = ep['sync']
        m = s['motion_check']
        if m.get('band_ms'):
            check = (f"{m['verdict']}: best {m['offset_ms']:+.0f} ms, consistent with "
                     f"{m['band_ms'][0]:+d}..{m['band_ms'][1]:+d} ms (r={m['r']})")
        else:
            check = m['verdict']
        lines.append(f"| {ep['episode_index']} | `{ep['source']}` | "
                     f"{s['frames_kept']}/{s['frames_recorded']} | {s['camera_latency_ms']} ms | "
                     f"{check} |")
    lines += ['', 'The image-motion check correlates how much each camera frame changes '
              'with how fast the arm moved. "consistent with" is every offset within one '
              'standard error of the best fit; an episode is only called MISALIGNED when '
              'that whole range is more than half a frame from zero.']
    lines += ['', '## Use', '', '```bash',
              '# look at it (LeRobot\'s own viewer)',
              f'ros2 run moveit_teleop_record view {root}', '',
              '# GR00T',
              'uv run python gr00t/experiment/launch_finetune.py \\',
              '    --base-model-path nvidia/GR00T-N1.7-3B \\',
              f'    --dataset-path {root} \\',
              '    --embodiment-tag NEW_EMBODIMENT \\',
              f'    --modality-config-path {root}/gr00t_modality_config.py',
              '```', '',
              'pi0.5 (openpi) reads this dataset with its pinned lerobot, but needs a '
              'TrainConfig and policy transform for this robot in its own source.', '']
    (root / 'README.md').write_text('\n'.join(lines))


# ---- verification ---------------------------------------------------------

def _psnr(a, b) -> float:
    mse = float(np.mean((a.astype(np.float32) - b.astype(np.float32)) ** 2))
    return 99.0 if mse == 0 else 10.0 * np.log10(255.0 ** 2 / mse)


def verify(root: Path, repo_id: str, bundles, size, chunk: int = 16) -> list:
    """Load the dataset back the way the training code does, and check it."""
    import torch
    from lerobot.common.datasets.lerobot_dataset import LeRobotDataset

    failures = []

    def check(ok, what):
        print(f"  {'ok  ' if ok else 'FAIL'} {what}")
        if not ok:
            failures.append(what)

    # Loading runs lerobot's own timestamp-sync check, to 0.1 ms.
    ds = LeRobotDataset(repo_id, root=root)
    info = json.loads((root / 'meta' / 'info.json').read_text())
    modality = json.loads((root / 'meta' / 'modality.json').read_text())
    check(info['codebase_version'] == 'v2.1',
          f"codebase_version {info['codebase_version']} (openpi's lerobot and GR00T read v2.1)")
    check(True, f'loaded with lerobot: {ds.num_episodes} episode(s), '
                f'{ds.num_frames} frames; timestamps on the 1/{ds.fps} s grid')

    state_dim = info['features']['observation.state']['shape'][0]
    action_dim = info['features']['action']['shape'][0]
    for part, dim in (('state', state_dim), ('action', action_dim)):
        spans = sorted((v['start'], v['end']) for v in modality[part].values())
        covered = spans[0][0] == 0 and spans[-1][1] == dim and all(
            a[1] == b[0] for a, b in zip(spans, spans[1:]))
        check(covered, f'modality.json {part} ranges {spans} tile [0:{dim}]')
    for key, v in modality['video'].items():
        ft = info['features'].get(v['original_key'], {})
        check(ft.get('dtype') == 'video',
              f"modality.json video '{key}' -> {v['original_key']} is a video feature")
    import ast
    config_src = (root / 'gr00t_modality_config.py').read_text()
    ast.parse(config_src)
    check(all(repr(g) in config_src for g in modality['state']),
          f"gr00t_modality_config.py parses and names groups {list(modality['state'])}")

    # Every exported row, against the arrays it came from.
    cams = bundles[0]['cameras']
    offset = ds.num_frames - sum(len(b['state']) for b in bundles)
    for b in bundles:
        n = len(b['state'])
        rows = ds.hf_dataset.select(range(offset, offset + n))
        st = np.stack([np.asarray(r) for r in rows['observation.state']])
        ac = np.stack([np.asarray(r) for r in rows['action']])
        check(np.allclose(st, b['state'], atol=1e-6) and np.allclose(ac, b['action'], atol=1e-6),
              f"{b['source']}: all {n} state/action rows match the aligned source")

        # Video frame k must BE source frame k. Compared against its neighbours
        # too: an off-by-one between parquet rows and video frames is invisible
        # in shapes and fatal in training.
        probe = sorted({1, n // 4, n // 2, 3 * n // 4, n - 2})
        misplaced, decisive = [], 0
        for k in probe:
            item = ds[offset + k]
            for cam in cams:
                got = (item[f'observation.images.{cam}'].permute(1, 2, 0).numpy()
                       * 255.0).round().clip(0, 255).astype(np.uint8)
                scores = {j: _psnr(got, decode(b['path'] / cam / f'{j:06d}.jpg', size))
                          for j in (k - 1, k, k + 1)}
                best = max(scores, key=scores.get)
                if scores[k] - max(scores[k - 1], scores[k + 1]) > 0.5:
                    decisive += 1
                if best != k:
                    misplaced.append((k, best, round(scores[k], 1)))
        check(not misplaced,
              f"{b['source']}: decoded video frames sit at their own rows "
              f'({len(probe)} probed, {decisive} decisive'
              + (f', misplaced {misplaced}' if misplaced else '') + ')')
        offset += n

    # Action chunks, the way both openpi and GR00T sample them.
    fps = ds.fps
    chunked = LeRobotDataset(repo_id, root=root,
                             delta_timestamps={'action': [k / fps for k in range(chunk)]})
    item = chunked[0]
    check(tuple(item['action'].shape) == (chunk, action_dim),
          f"action chunk of {chunk} at frame 0 -> shape {tuple(item['action'].shape)}")
    last = chunked[len(chunked) - 1]
    pad = last.get('action_is_pad')
    check(pad is not None and bool(pad[-1]) and not bool(pad[0]),
          'past the end of an episode the chunk is padded, not borrowed from the next')
    image = item[f'observation.images.{cams[0]}']
    check(image.dtype == torch.float32 and tuple(image.shape) == (3, size[1], size[0])
          if size else image.dtype == torch.float32,
          f'image decodes as {tuple(image.shape)} {image.dtype} in [0, 1]')
    return failures


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument('--bundles', nargs='+', required=True, type=Path)
    p.add_argument('--root', required=True, type=Path)
    p.add_argument('--repo-id', required=True)
    p.add_argument('--image-size', default='640x360')
    p.add_argument('--vcodec', default='libsvtav1', choices=['libsvtav1', 'h264'])
    p.add_argument('--export-config', required=True, type=Path,
                   help='JSON: {"robot": RobotModel.describe(), "dataset": settings}')
    p.add_argument('--append', action='store_true')
    p.add_argument('--overwrite', action='store_true')
    args = p.parse_args(argv)

    bundles = [load_bundle(b) for b in args.bundles]
    size = parse_size(args.image_size)
    export = json.loads(args.export_config.read_text())
    summary = write(bundles, args.root, args.repo_id, size, args.vcodec,
                    export, args.append, args.overwrite)
    if size is None:
        size = summary['size']
    print('\nverifying by loading it back with lerobot:')
    failures = verify(args.root, args.repo_id, bundles, size)
    if failures:
        print(f'\n{len(failures)} check(s) FAILED; do not train on this dataset.')
        return 1
    print(f"\ndataset ready: {args.root}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
